def maximo(a,b):
    if a > b:
        return a
    else:
        return b

def minimo(a,b):
    if a > b:
        return b
    else:
        return a


def son_iguales(a,b):
    if a == b:
        return True
    else:
        return False

def son_diferentes(a,b):
    if a != b:
        return True
    else:
        return False

